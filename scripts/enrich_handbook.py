def enrich(cards):
    cards = copy.deepcopy(cards)
    assert len(WORKFLOWS) == 30
    by_id = {c['id']: c for c in cards}
    assert len(by_id) == len(cards)
    for id, data in WORKFLOWS.items():
        by_id[id].update(copy.deepcopy(data))
        by_id[id]['source_ids'] = list(dict.fromkeys(
            by_id[id].get('source_ids', []) + [r['source_id'] for r in data['source_refs']]))
    # A generic worker PDF is not a primary source for tax rules.
    by_id['tax']['source_ids'] = []
    by_id['tax']['url'] = OFFICES['tax'][2]
    by_id['tax']['source'] = 'NTS · Easy Guide for Foreigners Year-End Tax Settlement 2025 (published 2026-01-06; online)'
    return cards

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT / 'assets/cards.json'
    cards = json.loads(path.read_text())
    enriched = enrich(cards)
    sources_path = ROOT / 'assets/sources.json'
    if sources_path.exists():
        sources = {s['id']: s for s in json.loads(sources_path.read_text())}
        for c in enriched:
            for r in c.get('source_refs', []):
                assert 1 <= r['page'] <= len(sources[r['source_id']]['pages']), (c['id'], r)
    if args.check:
        assert cards == enriched, 'Run python3 scripts/enrich_handbook.py and commit cards.json'
    else:
        path.write_text(json.dumps(enriched, ensure_ascii=False, indent=2) + '\n')
    print('Practical workflows: 30; total guides:', len(enriched))

if __name__ == '__main__':
    main()
